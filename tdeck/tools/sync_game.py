"""Make src/setup_rush/srush_game.c from the TI-84 game (one source for both devices).
The calculator file is the source of truth: setup-rush-ti84/game/src/main.c. This swaps its CE toolchain headers for
srush_shim.h and its main() for srush_main(), and turns on the T-Deck's touch build (SR_TOUCH)."""
import re, sys, pathlib
src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '/Users/maxmohammadi/setup-rush-ti84/game/src/main.c').read_text()
out = re.sub(r'#include <(graphx|keypadc|fileioc|sys/rtc|debug|intce)\.h>\n', '', src)
out = out.replace('#include <time.h>\n', '#include <time.h>\n#include "srush_shim.h"\n', 1)
out = re.sub(r'\bint main\(void\) \{', 'int srush_main(void) {', out)
out = '/* GENERATED by tools/setup_rush/sync_game.py from setup-rush-ti84/game/src/main.c: edit that file, then re-sync. */\n#define SR_TDECK 1\n#define SR_TOUCH 1\n' + out
out += '''
/* for the T-Deck's input layer and touch ring (srush_shim.c) */
int srush_scene(void) { return scene; }
uint16_t srush_ink(int which) { static const uint8_t I[5] = { C_GAIN, C_BEAR, C_TEXT, C_BG, C_ORANGE }; return gfx_palette[I[which % 5]]; }
'''
dst = pathlib.Path(__file__).resolve().parents[2] / 'src/setup_rush/srush_game.c'
dst.write_text(out)
print('wrote', dst, len(out), 'bytes')
