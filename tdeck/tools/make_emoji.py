"""The app's emoji candle pairs (setup-rush-app/src/game/emoji-candles.js EMOJI_SETS) as small sprites for the T-Deck:
each emoji from Twemoji (CC-BY 4.0, https://github.com/jdecked/twemoji), trimmed to its ink, fit into a SIZE square,
written as RGB565 plus a 4-bit alpha per pixel to src/platform/srush_emoji.h."""
from PIL import Image
import io, os, urllib.request
SIZE = 10
TWEMOJI = 'https://cdn.jsdelivr.net/gh/jdecked/twemoji@15.1.0/assets/72x72/%s.png'
SETS = [('DOTS', '1f7e2', '1f534'), ('ROCKET', '1f680', '1f480'), ('FIRE', '1f525', '2744'),
        ('MONEY', '1f4b0', '1f4b8'), ('DEGEN', '1f48e', '1f5d1'), ('VIBES', '1f319', '2600')]
CACHE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '../.pio/twemoji')
def fetch(code):
    os.makedirs(CACHE, exist_ok=True); path = os.path.join(CACHE, code + '.png')
    if not os.path.exists(path):
        with urllib.request.urlopen(TWEMOJI % code, timeout=30) as r: open(path, 'wb').write(r.read())
    return Image.open(path).convert('RGBA')
def sprite(ch):
    im = fetch(ch)
    im = im.crop(im.getbbox())
    k = SIZE / max(im.size); w, h = max(1, round(im.width * k)), max(1, round(im.height * k))
    # Pillow resizes RGBA with premultiplied alpha, so edges do not pick up the transparent black
    small = im.resize((w, h), Image.LANCZOS)
    out = Image.new('RGBA', (SIZE, SIZE), (0, 0, 0, 0)); out.paste(small, ((SIZE - w) // 2, (SIZE - h) // 2))
    px, al = [], []
    for y in range(SIZE):
        for x in range(SIZE):
            R, G, B, A = out.getpixel((x, y))
            px.append(((R >> 3) << 11) | ((G >> 2) << 5) | (B >> 3)); al.append(min(15, (A + 8) // 17))
    return px, al
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, '../src/platform/srush_emoji.h'), 'w') as f:
    f.write('/* generated by tools/make_emoji.py: the app\'s emoji candle pairs from Twemoji (CC-BY 4.0), %dx%d, RGB565 + 4-bit alpha */\n' % (SIZE, SIZE))
    f.write('#define SR_EMOJI_SETS %d\n#define SR_EMOJI_SIZE %d\n' % (len(SETS), SIZE))
    f.write('static const char *const SR_EMOJI_NAME[SR_EMOJI_SETS] = { %s };\n' % ', '.join('"%s"' % s[0] for s in SETS))
    f.write('static const uint16_t SR_EMOJI_PX[SR_EMOJI_SETS * 2][%d] = {\n' % (SIZE * SIZE))
    alphas = []
    for name, up, dn in SETS:
        for ch in (up, dn):
            px, al = sprite(ch); alphas.append(al)
            f.write('    { %s },\n' % ', '.join(str(v) for v in px))
    f.write('};\nstatic const uint8_t SR_EMOJI_A[SR_EMOJI_SETS * 2][%d] = {\n' % (SIZE * SIZE // 2))
    for al in alphas:
        f.write('    { %s },\n' % ', '.join(str(al[i] | (al[i + 1] << 4)) for i in range(0, len(al), 2)))
    f.write('};\n')
print('ok')
