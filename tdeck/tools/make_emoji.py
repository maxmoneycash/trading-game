"""The app's emoji candle pairs (setup-rush-app/src/game/emoji-candles.js EMOJI_SETS) as small sprites for the T-Deck:
each emoji drawn from Apple Color Emoji at 160 px, trimmed to its ink, fit into a SIZE square, written as RGB565 plus a
4-bit alpha per pixel to src/setup_rush/srush_emoji.h. Run on a Mac (it needs the system emoji font)."""
from PIL import Image, ImageDraw, ImageFont
import os
SIZE = 10
SETS = [('DOTS', '\U0001F7E2', '\U0001F534'), ('ROCKET', '\U0001F680', '\U0001F480'), ('FIRE', '\U0001F525', '❄️'),
        ('MONEY', '\U0001F4B0', '\U0001F4B8'), ('DEGEN', '\U0001F48E', '\U0001F5D1️'), ('VIBES', '\U0001F319', '☀️')]
font = ImageFont.truetype('/System/Library/Fonts/Apple Color Emoji.ttc', 160)
def sprite(ch):
    im = Image.new('RGBA', (240, 240), (0, 0, 0, 0))
    ImageDraw.Draw(im).text((120, 120), ch, font=font, embedded_color=True, anchor='mm')
    im = im.crop(im.getbbox())
    k = SIZE / max(im.size); w, h = max(1, round(im.width * k)), max(1, round(im.height * k))
    # Pillow resizes RGBA with premultiplied alpha, so edges do not pick up the transparent black
    small = im.resize((w, h), Image.LANCZOS)
    out = Image.new('RGBA', (SIZE, SIZE), (0, 0, 0, 0)); out.paste(small, ((SIZE - w) // 2, (SIZE - h) // 2))
    px, al = [], []
    for y in range(SIZE):
        for x in range(SIZE):
            R, G, B, A = out.getpixel((x, y))
            px.append(((R >> 3) << 11) | ((G >> 2) << 5) | (B >> 3)); al.append(min(15, (A + 8) // 17))
    return px, al
here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, '../src/platform/srush_emoji.h'), 'w') as f:
    f.write('/* generated by tools/setup_rush/make_emoji.py: the app\'s emoji candle pairs, %dx%d, RGB565 + 4-bit alpha */\n' % (SIZE, SIZE))
    f.write('#define SR_EMOJI_SETS %d\n#define SR_EMOJI_SIZE %d\n' % (len(SETS), SIZE))
    f.write('static const char *const SR_EMOJI_NAME[SR_EMOJI_SETS] = { %s };\n' % ', '.join('"%s"' % s[0] for s in SETS))
    f.write('static const uint16_t SR_EMOJI_PX[SR_EMOJI_SETS * 2][%d] = {\n' % (SIZE * SIZE))
    alphas = []
    for name, up, dn in SETS:
        for ch in (up, dn):
            px, al = sprite(ch); alphas.append(al)
            f.write('    { %s },\n' % ', '.join(str(v) for v in px))
    f.write('};\nstatic const uint8_t SR_EMOJI_A[SR_EMOJI_SETS * 2][%d] = {\n' % (SIZE * SIZE // 2))
    for al in alphas:
        f.write('    { %s },\n' % ', '.join(str(al[i] | (al[i + 1] << 4)) for i in range(0, len(al), 2)))
    f.write('};\n')
print('ok')
