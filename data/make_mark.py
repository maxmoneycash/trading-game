"""The app's R mark (setup-rush-app/public/mark-r.png) as a 2-bit coverage bitmap for the intro: game/src/mark.h.
Four levels per pixel (none, a third, two thirds, full), four pixels a byte, rows top to bottom."""
from PIL import Image
import os
H = 80
here = os.path.dirname(os.path.abspath(__file__))
im = Image.open(os.path.join(here, 'brand/mark-r.png')).convert('RGBA')
a = im.split()[3].crop(im.getbbox())
W = round(a.width * H / a.height)
a = a.resize((W * 4, H * 4), Image.LANCZOS).resize((W, H), Image.BOX)
lv = [min(3, round(a.getpixel((x, y)) * 3 / 255)) for y in range(H) for x in range(W)]
bw = (W + 3) // 4
out = bytearray()
for y in range(H):
    for b in range(bw):
        v = 0
        for i in range(4):
            x = b * 4 + i
            v |= (lv[y * W + x] if x < W else 0) << (2 * i)
        out.append(v)
with open(os.path.join(here, '../game/src/mark.h'), 'w') as f:
    f.write('/* generated by data/make_mark.py from the app\'s R mark: 2 bits a pixel, 4 pixels a byte */\n')
    f.write(f'#define MARK_W {W}\n#define MARK_H {H}\n#define MARK_BW {bw}\nstatic const uint8_t MARK[{len(out)}] = {{\n')
    for i in range(0, len(out), 24): f.write('    ' + ', '.join(str(v) for v in out[i:i + 24]) + ',\n')
    f.write('};\n')
print(W, H, len(out))
